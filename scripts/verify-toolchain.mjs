import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const lock = JSON.parse(readFileSync(new URL('../toolchains.lock.json', import.meta.url), 'utf8'));
const expectedNode = `v${lock.node}`;
const expectedCmake = lock.cmake;
const expectedQt = lock.qt;
const expectedWix = lock.wix;
const expectedDotnet = lock.dotnet;
if (process.version !== expectedNode) throw new Error(`Node ${expectedNode} is required; found ${process.version}`);
const cmake = spawnSync('cmake', ['--version'], { encoding: 'utf8' });
if (cmake.status !== 0) throw new Error(`CMake is required; install ${expectedCmake} from toolchains.lock.json`);
const actualCmake = /cmake version ([^\s]+)/.exec(cmake.stdout)?.[1];
if (actualCmake !== expectedCmake) throw new Error(`CMake ${expectedCmake} is required; found ${actualCmake ?? 'unknown'}`);
const qt = spawnSync('qtpaths6', ['--qt-version'], { encoding: 'utf8' });
if (qt.status !== 0 || qt.stdout.trim() !== expectedQt) throw new Error(`Qt ${expectedQt} is required; found ${qt.stdout.trim() || 'missing'}`);
const wix = spawnSync('wix', ['--version'], { encoding: 'utf8' });
const actualWix = /^(\d+\.\d+\.\d+)/.exec(wix.stdout.trim())?.[1];
if (wix.status !== 0 || actualWix !== expectedWix) throw new Error(`WiX ${expectedWix} is required; found ${actualWix ?? 'missing'}`);
const dotnet = spawnSync('dotnet', ['--version'], { encoding: 'utf8' });
if (dotnet.status !== 0 || dotnet.stdout.trim() !== expectedDotnet) throw new Error(`.NET SDK ${expectedDotnet} is required; found ${dotnet.stdout.trim() || 'missing'}`);
const buildTools = 'C:\\BuildTools\\VS2022\\VC\\Tools\\MSVC';
const expectedMsvc = lock.msvcTools;
if (!existsSync(buildTools) || !readdirSync(buildTools).some((name) => name.startsWith(`${expectedMsvc}.`))) throw new Error(`MSVC ${expectedMsvc} is required`);
const sdk = `C:\\Program Files (x86)\\Windows Kits\\10\\Include\\${lock.windowsSdk}`;
if (!existsSync(sdk)) throw new Error(`Windows SDK ${lock.windowsSdk} is required`);
console.log(`toolchain: Node ${expectedNode}, CMake ${expectedCmake}, Qt ${expectedQt}, WiX ${expectedWix}, .NET ${expectedDotnet}, MSVC ${expectedMsvc}, SDK ${lock.windowsSdk}`);
